    /** Satu panel per menu; panel lama dibuang agar datanya tidak ikut tertinggal. */
    private void tampilPanel(String menu) {
        javax.swing.JPanel panel;
        javax.swing.JButton aktif;
        switch (menu) {
            case "promosi":
                panel = new KelolaPromosi();
                aktif = btnMenuPromosi;
                break;
            case "analisis":
                AnalisisPenjualan analisis = new AnalisisPenjualan();
                analisis.setPeninjauDiskon(this::tinjauPromosiBatch);
                panel = analisis;
                aktif = btnMenuAnalisis;
                break;
            default:
                panel = new KelolaProduk();
                aktif = btnMenuProduk;
                break;
        }
        GayaNavigasi.tandaiAktif(aktif, btnMenuProduk, btnMenuPromosi, btnMenuAnalisis);
        pnlKonten.removeAll();
        pnlKonten.add(panel, new org.netbeans.lib.awtextra.AbsoluteConstraints(0, 0, 1095, 805));
        pnlKonten.revalidate();
        pnlKonten.repaint();
    }

    /** Tautan "Tinjau diskon" di Analisis: pindah ke Kelola Promosi lalu buka form batch ini. */
    private void tinjauPromosiBatch(Stok stok) {
        tampilPanel("promosi");
        for (java.awt.Component komponen : pnlKonten.getComponents()) {
            if (komponen instanceof KelolaPromosi) {
                ((KelolaPromosi) komponen).bukaFormBatch(stok);
                return;
            }
        }
    }
