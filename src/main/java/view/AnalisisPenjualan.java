    // muat laporan
    private void muatData() {
        LocalDate awal, akhir;
        try {
            awal = Format.bacaTanggal(txtTglAwal.getText());
            akhir = Format.bacaTanggal(txtTglAkhir.getText());
        } catch (DateTimeParseException ex) {
            Pesan.peringatan(this, "Tanggal awal dan akhir harus berformat dd/MM/yyyy.");
            return;
        }
        if (akhir.isBefore(awal)) {
            Pesan.peringatan(this, "Tanggal akhir tidak boleh mendahului tanggal awal.");
            return;
        }

        try {
            long omzet = analisisController.omzet(awal, akhir);
            int unit = analisisController.unitTerjual(awal, akhir);
            int transaksi = analisisController.jumlahTransaksi(awal, akhir);

            lblOmzet.setText(Format.rupiah(omzet));
            lblUnit.setText(unit + " unit");
            lblTrx.setText(transaksi + " transaksi");
            lblRentang.setText(Format.tanggal(awal) + " - " + Format.tanggal(akhir));

            muatRincian(awal, akhir);
            muatPrioritas();
            grafik.isi(analisisController.trenOmzetHarian(awal, akhir));
        } catch (SQLException ex) {
            Pesan.gagalDatabase(this, ex);
        }
    }

    // export excel
    private void eksporExcel() {
        LocalDate awal, akhir;
        try {
            awal = Format.bacaTanggal(txtTglAwal.getText());
            akhir = Format.bacaTanggal(txtTglAkhir.getText());
        } catch (DateTimeParseException ex) {
            Pesan.peringatan(this, "Tanggal awal dan akhir harus berformat dd/MM/yyyy.");
            return;
        }
        if (akhir.isBefore(awal)) {
            Pesan.peringatan(this, "Tanggal akhir tidak boleh mendahului tanggal awal.");
            return;
        }

        JFileChooser pemilih = new JFileChooser();
        pemilih.setDialogTitle("Simpan Laporan Analisis Penjualan");
        pemilih.setFileFilter(new FileNameExtensionFilter("Berkas Excel (.xlsx)", "xlsx"));
        pemilih.setSelectedFile(new File(namaBawaan(awal, akhir)));
        if (pemilih.showSaveDialog(SwingUtilities.getWindowAncestor(this))
                != JFileChooser.APPROVE_OPTION) {
            return;
        }

        File tujuan = pemilih.getSelectedFile();
        if (!tujuan.getName().toLowerCase().endsWith(".xlsx")) {
            tujuan = new File(tujuan.getAbsoluteFile() + ".xlsx");
        }
        try {
            laporanController.ekspor(awal, akhir, tujuan, Sesi.username());
            Pesan.sukses(this, "Laporan tersimpan di:\n" + tujuan.getAbsolutePath());
        } catch (SQLException ex) {
            Pesan.gagalDatabase(this, ex);
        } catch (IOException ex) {
            Pesan.galat(this, "Gagal menulis berkas Excel.", ex);
        }
    }

    // nama file laporan
    private static String namaBawaan(LocalDate awal, LocalDate akhir) {
        return "Laporan Penjualan "
                + Format.tanggal(awal).replace("/", "-") + " s/d "
                + Format.tanggal(akhir).replace("/", "-") + ".xlsx";
    }

    // isi tabel rincian
    private void muatRincian(LocalDate awal, LocalDate akhir) throws SQLException {
        List<BarisAnalisis> rincian = analisisController.rincianPerProduk(awal, akhir);
        daftarRincian = rincian;
        rentangAwal = awal;
        rentangAkhir = akhir;
        tabelModel.setRowCount(0);
        long totalOmzet = 0;
        long totalDiskon = 0;
        int totalUnit = 0;
        for (BarisAnalisis b : rincian) {
            tabelModel.addRow(new Object[]{
                Format.judul(b.getNamaProduk()), b.getBarcode(),
                b.getJumlahTerjual(), Format.rupiah(b.getOmzet()),
                Format.rupiah(b.getTotalDiskon()), "Detail"
            });
            totalOmzet += b.getOmzet();
            totalDiskon += b.getTotalDiskon();
            totalUnit += b.getJumlahTerjual();
        }
        lblTotalRincian.setText(totalUnit + " unit terjual, omzet "
                + Format.rupiah(totalOmzet) + ", diskon " + Format.rupiah(totalDiskon));
    }

    // muat prioritas stok
    private void muatPrioritas() throws SQLException {
        prioritas = analisisController.prioritasBatch();
        tampilkanPrioritas(lblPrio1, lblHari1, prioritas, 0);
        tampilkanPrioritas(lblPrio2, lblHari2, prioritas, 1);
    }

    /** Jembatan ke Kelola Promosi; dipasang ManajerFrame agar panel ini tak perlu tahu navigasi frame. */
    public void setPeninjauDiskon(java.util.function.Consumer<Stok> peninjau) {
        peninjauDiskon = peninjau;
    }

    // tinjau diskon
    private void tinjauDiskon() {
        if (prioritas.isEmpty()) {
            Pesan.info(this, "Belum ada batch stok yang mendekati kedaluwarsa.");
            return;
        }
        if (peninjauDiskon != null) {
            peninjauDiskon.accept(prioritas.get(0));
        }
    }

    // tampil prioritas
    private void tampilkanPrioritas(javax.swing.JLabel isi, javax.swing.JLabel sisa,
                                    List<Stok> prioritas, int indeks) {
        if (indeks >= prioritas.size()) {
            isi.setText(indeks == 0
                    ? "<html>Belum ada batch yang<br>mendekati kedaluwarsa.</html>"
                    : "<html>Tidak ada batch lain<br>pada daftar prioritas.</html>");
            sisa.setText("");
            sisa.setVisible(false);
            return;
        }
        Stok s = prioritas.get(indeks);
        isi.setText("<html><b>" + Format.judul(s.getNamaProduk())
                + " (" + s.getJumlah() + " unit)</b><br>" + s.getIdStok()
                + ", exp " + Format.tanggal(s.getTglKedaluwarsa()) + "</html>");
        sisa.setText(s.sisaHari() + " hari");
        sisa.setVisible(true);
    }

    // dialog detail produk
    private void bukaDetail(int baris) {
        if (baris < 0 || baris >= daftarRincian.size() || rentangAwal == null) {
            return;
        }
        BarisAnalisis produk = daftarRincian.get(baris);
        try {
            List<PenjualanProduk> riwayat =
                    analisisController.riwayatProduk(produk.getBarcode(), rentangAwal, rentangAkhir);
            if (riwayat.isEmpty()) {
                Pesan.info(this, "Tidak ada transaksi " + produk.getNamaProduk()
                        + " pada rentang ini.");
                return;
            }
            new DetailPenjualanProdukDialog(SwingUtilities.getWindowAncestor(this),
                    produk.getNamaProduk(), produk.getBarcode(), rentangAwal, rentangAkhir, riwayat)
                    .setVisible(true);
        } catch (SQLException ex) {
            Pesan.gagalDatabase(this, ex);
        }
    }

    private static final class GrafikBar extends javax.swing.JPanel {

        private static final int KIRI = 56;
        private static final int ATAS = 16;
        private static final int BAWAH = 20;

        private Map<LocalDate, Long> data = Map.of();
        private LocalDate[] tanggal = new LocalDate[0];
        private int terpilih = -1;

        // konstruktor grafik
        GrafikBar() {
            setToolTipText("");
            addMouseMotionListener(new java.awt.event.MouseAdapter() {
                @Override public void mouseMoved(java.awt.event.MouseEvent e) {
                    int indeks = indeksDi(e.getPoint());
                    if (indeks != terpilih) {
                        terpilih = indeks;
                        repaint();
                    }
                }
            });
            addMouseListener(new java.awt.event.MouseAdapter() {
                @Override public void mouseExited(java.awt.event.MouseEvent e) {
                    if (terpilih != -1) {
                        terpilih = -1;
                        repaint();
                    }
                }
            });
        }

        // isi data grafik
        void isi(Map<LocalDate, Long> data) {
            this.data = new TreeMap<>(data);
            this.tanggal = this.data.keySet().toArray(new LocalDate[0]);
            this.terpilih = -1;
            repaint();
        }

        // tooltip grafik
        @Override public String getToolTipText(java.awt.event.MouseEvent e) {
            int indeks = indeksDi(e.getPoint());
            if (indeks < 0) {
                return null;
            }
            LocalDate hari = tanggal[indeks];
            return "<html><b>" + Format.tanggalPanjang(hari) + "</b><br>"
                    + Format.rupiah(data.get(hari)) + "</html>";
        }

        // indeks bar grafik
        private int indeksDi(java.awt.Point titik) {
            if (tanggal.length == 0 || titik.x < KIRI || titik.y > getHeight() - BAWAH) {
                return -1;
            }
            int jarak = (getWidth() - KIRI - 6) / tanggal.length;
            if (jarak <= 0) {
                return -1;
            }
            int indeks = (titik.x - KIRI) / jarak;
            return Math.min(indeks, tanggal.length - 1);
        }

        // gambar grafik
        @Override protected void paintComponent(Graphics g) {
            super.paintComponent(g);
            if (tanggal.length == 0) {
                g.setColor(new Color(100, 116, 139));
                g.setFont(new Font("Segoe UI", Font.ITALIC, 12));
                g.drawString("Belum ada transaksi pada rentang ini.", KIRI, getHeight() / 2);
                return;
            }
            Graphics2D g2 = (Graphics2D) g;
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);

            int areaLebar = getWidth() - KIRI - 6;
            int areaTinggi = getHeight() - ATAS - BAWAH;
            long tertinggi = data.values().stream().mapToLong(Long::longValue).max().orElse(1);
            if (tertinggi == 0) {
                tertinggi = 1;
            }
            g2.setFont(new Font("Segoe UI", Font.PLAIN, 9));
            java.awt.FontMetrics fm = g2.getFontMetrics();
            for (int bagian = 0; bagian <= 4; bagian++) {
                long nilai = tertinggi * bagian / 4;
                int y = ATAS + areaTinggi - areaTinggi * bagian / 4;
                if (bagian == 0) {
                    g2.setColor(new Color(203, 213, 225));
                    g2.drawLine(KIRI, y, KIRI + areaLebar, y);
                }
                g2.setColor(new Color(100, 116, 139));
                String label = bagian == 0 ? "0" : Format.rupiahPendek(nilai);
                g2.drawString(label, KIRI - 8 - fm.stringWidth(label), y + 3);
            }

            int jarak = Math.max(2, areaLebar / tanggal.length);
            int lebarBar = Math.max(2, jarak - 5);
            boolean adaRuangLabel = jarak >= 34;
            int tiapLabel = jarak >= 12 ? 1 : (int) Math.ceil(12.0 / jarak);

            for (int i = 0; i < tanggal.length; i++) {
                LocalDate hari = tanggal[i];
                long nilai = data.get(hari);
                int tinggiBar = (int) ((double) nilai / tertinggi * areaTinggi);
                int x = KIRI + i * jarak;
                int atas = ATAS + areaTinggi - tinggiBar;

                g2.setColor(i == terpilih ? new Color(16, 40, 79) : new Color(71, 111, 165));
                g2.fillRoundRect(x, atas, lebarBar, tinggiBar, 5, 5);

                if (adaRuangLabel || i == terpilih) {
                    String angka = Format.rupiahPendek(nilai);
                    g2.setColor(new Color(16, 40, 79));
                    g2.setFont(new Font("Segoe UI", Font.BOLD, 9));
                    g2.drawString(angka, x + lebarBar / 2 - g2.getFontMetrics().stringWidth(angka) / 2,
                            Math.max(atas - 4, 9));
                    g2.setFont(new Font("Segoe UI", Font.PLAIN, 9));
                }
                if (i % tiapLabel == 0) {
                    g2.setColor(new Color(100, 116, 139));
                    g2.drawString(String.valueOf(hari.getDayOfMonth()),
                            x + lebarBar / 2 - 4, getHeight() - 6);
                }
            }
        }
    }
