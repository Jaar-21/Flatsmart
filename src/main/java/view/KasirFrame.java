    /** Satu panel per menu; panel lama dibuang agar datanya tidak ikut tertinggal. */
    private void tampilPanel(String menu) {
        javax.swing.JPanel panel;
        javax.swing.JButton aktif;
        switch (menu) {
            case "tagihan":
                panel = new PembayaranTagihan();
                aktif = btnMenuTagihan;
                break;
            case "riwayat":
                panel = new LihatTransaksi();
                aktif = btnMenuRiwayat;
                break;
            default:
                panel = new TransaksiPenjualan();
                aktif = btnMenuPenjualan;
                break;
        }
        GayaNavigasi.tandaiAktif(aktif, btnMenuPenjualan, btnMenuTagihan, btnMenuRiwayat);
        pnlKonten.removeAll();
        pnlKonten.add(panel, new org.netbeans.lib.awtextra.AbsoluteConstraints(0, 0, 1095, 805));
        pnlKonten.revalidate();
        pnlKonten.repaint();
    }
