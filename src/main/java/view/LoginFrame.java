    // tombol masuk
    private void btnMasukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMasukActionPerformed
        lblPesan.setText("");
        try {
            String username = Pemeriksa.teks(txtUsername.getText(), "Username", 50);
            Pengguna pengguna = authController.login(username,
                    new String(pwdPassword.getPassword()));
            if (pengguna.isManajer()) {
                new ManajerFrame().setVisible(true);
            } else {
                new KasirFrame().setVisible(true);
            }
            dispose();
        } catch (IllegalArgumentException e) {
            lblPesan.setText(e.getMessage());
            pwdPassword.setText("");
            pwdPassword.requestFocus();
        } catch (SQLException e) {
            Pesan.galat(this, "Tidak dapat terhubung ke database.\n"
                    + "Periksa koneksi lalu coba lagi.", e);
            txtUsername.requestFocus();
        }
    }//GEN-LAST:event_btnMasukActionPerformed

